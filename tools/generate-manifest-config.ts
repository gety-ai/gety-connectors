// Generates src/gen/manifest.d.ts (the `ManifestConfig` type) from the
// manifest.json of the connector in the working directory.

interface Manifest {
	config?: {
		fields?: ManifestConfigField[];
	};
}

interface ManifestConfigField {
	id: string;
	type: string;
	required?: boolean;
}

interface ConfigNode {
	children: Map<string, ConfigNode>;
	type: string | null;
	optional: boolean;
}

const fieldTypeMap: Record<string, string> = {
	text: 'string',
	password: 'string',
	number: 'number',
	checkbox: 'boolean',
	dropdown: 'string',
	directory: 'string',
};

if (import.meta.main) {
	await generateManifestConfig();
}

export async function generateManifestConfig(): Promise<void> {
	const manifest = JSON.parse(
		await Deno.readTextFile('manifest.json'),
	) as Manifest;
	const fields = manifest.config?.fields ?? [];
	const source = [
		'// Generated by tools/generate-manifest-config.ts from manifest.json. Do not edit.',
		'',
		renderConfigType(fields),
		'',
	].join('\n');

	await Deno.mkdir('src/gen', { recursive: true });
	await Deno.writeTextFile('src/gen/manifest.d.ts', source);
}

function renderConfigType(fields: ManifestConfigField[]): string {
	if (fields.length === 0) {
		return 'export interface ManifestConfig extends Record<string, never> {}';
	}

	const root: ConfigNode = {
		children: new Map(),
		type: null,
		optional: false,
	};
	for (const field of fields) {
		addField(root, field);
	}

	return `export interface ManifestConfig ${renderNode(root, 0)}`;
}

function addField(root: ConfigNode, field: ManifestConfigField): void {
	const tsType = fieldTypeMap[field.type];
	if (tsType == null) {
		throw new Error(`Unsupported manifest config field type "${field.type}".`);
	}

	// A field is optional when `required` is explicitly false. Nested groups are
	// optional only when every leaf under them is optional.
	const optional = field.required === false;

	const parts = field.id.split('.');
	let node = root;
	for (const [index, part] of parts.entries()) {
		if (part === '') {
			throw new Error(`Invalid manifest config field id "${field.id}".`);
		}

		const isLeaf = index === parts.length - 1;
		let child = node.children.get(part);
		if (child == null) {
			child = {
				children: new Map(),
				type: null,
				optional: isLeaf ? optional : true,
			};
			node.children.set(part, child);
		}

		if (isLeaf) {
			if (child.children.size > 0 || child.type != null) {
				throw new Error(`Duplicate manifest config field id "${field.id}".`);
			}
			child.type = tsType;
			child.optional = optional;
			return;
		}

		if (child.type != null) {
			throw new Error(`Conflicting manifest config field id "${field.id}".`);
		}
		// A group stays optional only while all of its leaves are optional.
		child.optional = child.optional && true;
		node = child;
	}
}

function renderNode(node: ConfigNode, depth: number): string {
	const lines = ['{'];
	for (const [key, child] of node.children) {
		const value = child.type ?? renderNode(child, depth + 1);
		const optionalMark = isNodeOptional(child) ? '?' : '';
		lines.push(
			`${'\t'.repeat(depth + 1)}${propertyKey(key)}${optionalMark}: ${value};`,
		);
	}
	lines.push(`${'\t'.repeat(depth)}}`);
	return lines.join('\n');
}

/**
 * A leaf is optional when its field declared `required: false`. A group is
 * optional only when every leaf under it is optional, so that a required nested
 * field still forces the group to be present.
 */
function isNodeOptional(node: ConfigNode): boolean {
	if (node.type != null) {
		return node.optional;
	}
	for (const child of node.children.values()) {
		if (!isNodeOptional(child)) {
			return false;
		}
	}
	return node.children.size > 0;
}

function propertyKey(key: string): string {
	return /^[$A-Z_a-z][$\w]*$/.test(key) ? key : JSON.stringify(key);
}
